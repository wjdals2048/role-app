/** 우리가 문항을 적어 두지 않은 역할(직접 추가한 역할 등)에 쓰는 공통 질문. 역할 이름만 끼워 넣는다. */
export const genericQuiz = (name) => {
  const n = String(name || '이 역할').trim() || '이 역할';
  return Q(`‘${n}’ 역할을 맡는 일이 부담스러워요.`, `‘${n}’ 역할을 해내면 보람을 느낄 것 같아요.`, `‘${n}’ 역할을 맡아 본 경험이 있어요.`);
};
/** 역할의 질문 3개: 종류별 문항이 있으면 그것을, 없으면 공통 질문을 쓴다. */
export const quizFor = (role, kind) => (kind && QUIZ[kind]) || genericQuiz(role?.name);

/** 답 버튼: 결과를 바꾸는 건 맨 앞 'y'(네/있어요)뿐이다. 가운데·마지막 답은 근거로 쓰지 않는다(건너뜀 = 가운데 답). */
export const ANSWERS = {
  burden: [['y', '네'], ['m', '잘 모르겠어요'], ['n', '아니요']],
  reward: [['y', '네'], ['m', '잘 모르겠어요'], ['n', '아니요']],
  exp: [['y', '있어요'], ['m', '조금 있어요'], ['n', '없어요']],
};

/** a = { burden, reward, exp } 각각 'y' | 'm' | 'n' | 없음(건너뜀). 하나도 답하지 않았으면 null. */
export function suggestFromAnswers(a = {}) {
  if (!a.burden && !a.reward && !a.exp) return null;
  const b = a.burden === 'y', r = a.reward === 'y', e = a.exp === 'y';
  if (b && !r) return { pref: 'avoid', why: '부담스럽다고 답했어요' };
  if (r && !b) return { pref: 'want', why: '보람을 느낀다고 답했어요' };
  if (b && r) return e ? { pref: 'want', why: '부담도 있지만 보람과 경험이 있다고 답했어요' } : { pref: 'ok', why: '부담과 보람을 모두 느낀다고 답했어요' };
  return { pref: 'ok', why: e ? '경험은 있지만 부담이나 보람이 크지 않다고 답했어요' : '부담이나 보람이 크지 않다고 답했어요' };
}
